-- =============================================================
-- 44 · As categorias da Shopee ganham nicho
--
-- O feed de produto da Shopee (D-058) traz `global_catid2`, que é a
-- categoria de segundo nível do item. Sem mapa, todo anúncio dela
-- entraria sem nicho — e anúncio sem nicho não acha canal, então o
-- catálogo encheria e a fila continuaria vazia. `nenhum_canal_do_nicho`
-- já é um dos motivos de reprovação mais comuns.
--
-- POR QUE NA MESMA TABELA DO MERCADO LIVRE
--
-- `nicho_dominio` existe desde a D-023 com a chave `MLB-*`. A chave da
-- Shopee é `SHOPEE-<catid2>`, no mesmo formato, na mesma tabela: o
-- coletor de cada loja procura pela sua chave e as duas convivem sem
-- colidir. Mapear categoria nova continua sendo `insert` de uma linha,
-- que era o ponto da D-023.
--
-- COMO ESTE MAPA FOI FEITO
--
-- Lendo os dois feeds inteiros e agrupando por categoria. São 255
-- categorias de segundo nível; 240 receberam nicho por
-- correspondência de nome, e as 15 restantes ficaram de fora de
-- propósito — são as que não têm nicho nosso equivalente.
--
-- O coletor imprime, ao fim de cada execução, as categorias que
-- apareceram e não estão aqui. É por ali que este mapa cresce.
-- =============================================================

-- A tabela é chaveada por (operacao, marketplace, dominio), então a
-- Shopee poderia usar o número da categoria puro sem colidir com o ML.
-- O prefixo fica assim mesmo: `anuncio.dominio_externo` é coluna
-- compartilhada entre as lojas, e um número solto ali não diz de quem é
-- para quem estiver lendo o banco às três da manhã.
